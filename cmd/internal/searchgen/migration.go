package searchgen

// migration.go emits the Postgres migration artifacts for an INDEXED searchable
// resource (WS-041 SD-7, FR-C2). The INDEXED strategy trades zero-migration JIT
// for scale: a persisted `search_vector` generated column plus a GIN index, so a
// List no longer recomputes to_tsvector(…) per query but matches an indexed
// column (FR-C3).
//
// # Why two migration files, not one
//
// CREATE INDEX CONCURRENTLY cannot run inside a transaction block, and the
// migration engine (infobloxopen/migrate) sends a multi-statement file as one
// implicit transaction — so the index MUST be the sole statement in its own file
// (FM-6, migrations.README.md.tmpl). The generated column is an ordinary
// transactional ALTER, so it lives in a separate, earlier file. Both are pure
// Postgres DDL: SQLite has no tsvector and keeps the query-time LIKE fallback with
// no persisted column (FR-C3), so these files are never applied on SQLite (the
// module runner ignores the versioned files on SQLite, materializing the dev DB via
// AutoMigrate).
//
// # Idempotency (FM-4)
//
// The file set is a pure, deterministic function of (table, compiled vector,
// text_config, version) — no filesystem read, no counter, no timestamp — so
// `make generate` twice yields byte-identical files (AC-7). The version is a
// FIXED number the generator allocates in a reserved band (see the generators'
// searchMigrationBaseVersion), NOT the next-free number on disk, which is what
// keeps regeneration diff-clean rather than appending a fresh migration each run.

import "fmt"

// IndexColumn is the fixed name of the persisted tsvector column (SD-7). It is a
// DB-computed generated column, never a proto field / GORM model field, so it is
// invisible to the API surface and to SQLite AutoMigrate.
const IndexColumn = "search_vector"

// IndexName returns the deterministic GIN index name for a table's search_vector
// column: "<table>_search_gin".
func IndexName(table string) string { return table + "_search_gin" }

// MigrationFile is one generated SQL migration file: a golang-migrate base name
// ("<version>_<desc>.{up,down}.sql") and its SQL body.
type MigrationFile struct {
	Name string
	Body string
}

// BuildIndexedMigration returns the four migration files (an up/down pair for the
// generated column and an up/down pair for the CONCURRENTLY GIN index) for an
// INDEXED resource backing table, versioned from columnVersion (the index takes
// columnVersion+1).
//
// postgresVector is the compiled search vector (Compiled.PostgresVector): the same
// coalesced source union the JIT predicate feeds to_tsvector, incl. any
// sql/postgres source (FR-C2). It is wrapped in to_tsvector('<textConfig>', …).
// Both the config and the vector are compiler output, never the user's query
// string, so nothing here is a runtime injection surface (the query term is a
// bound parameter in the List predicate, FM-3).
func BuildIndexedMigration(table, textConfig, postgresVector string, columnVersion int) []MigrationFile {
	col := IndexColumn
	idx := IndexName(table)
	cfg := textConfig
	if cfg == "" {
		cfg = "simple"
	}
	colBase := fmt.Sprintf("%04d_%s_search_vector", columnVersion, table)
	idxBase := fmt.Sprintf("%04d_%s_search_gin", columnVersion+1, table)

	const header = "-- Code generated by devedge-sdk full-text search (WS-041). DO NOT EDIT.\n"

	colUp := header +
		fmt.Sprintf("-- INDEXED strategy: a persisted tsvector generated column for the %q table.\n", table) +
		fmt.Sprintf("ALTER TABLE %s\n", table) +
		fmt.Sprintf("    ADD COLUMN %s tsvector\n", col) +
		fmt.Sprintf("    GENERATED ALWAYS AS (to_tsvector('%s', %s)) STORED;\n", cfg, postgresVector)
	colDown := header +
		fmt.Sprintf("ALTER TABLE %s DROP COLUMN IF EXISTS %s;\n", table, col)

	// The index up file's SOLE statement is the CONCURRENTLY create (FM-6): no
	// transaction wrapper, no companion statement.
	idxUp := header +
		"-- CREATE INDEX CONCURRENTLY must be the SOLE statement in its migration file:\n" +
		"-- Postgres forbids it inside a transaction block and the engine sends a\n" +
		"-- multi-statement file as one implicit transaction (FM-6).\n" +
		fmt.Sprintf("CREATE INDEX CONCURRENTLY %s ON %s USING GIN (%s);\n", idx, table, col)
	idxDown := header +
		fmt.Sprintf("DROP INDEX CONCURRENTLY IF EXISTS %s;\n", idx)

	return []MigrationFile{
		{Name: colBase + ".up.sql", Body: colUp},
		{Name: colBase + ".down.sql", Body: colDown},
		{Name: idxBase + ".up.sql", Body: idxUp},
		{Name: idxBase + ".down.sql", Body: idxDown},
	}
}
